"""Generate weak default definitions for every import the recompiled code references.

Real implementations elsewhere in runtime/ override these at link time.
usage: gen_import_stubs.py out/ppc/ppc_recomp_shared.h runtime/kernel/import_stubs.cpp
"""
import re, sys

names = sorted(set(re.findall(r'PPC_EXTERN_FUNC\(__imp__(\w+)\);', open(sys.argv[1]).read())))
with open(sys.argv[2], 'w') as out:
    out.write('// Generated by tools/gen_import_stubs.py. Do not edit.\n')
    out.write('#include "../guest.h"\n\nnamespace rt { void UnimplementedImport(const char* name, PPCContext& ctx); }\n\n')
    for n in names:
        out.write('__attribute__((weak)) PPC_FUNC(__imp__%s) { ::rt::UnimplementedImport("%s", ctx); }\n' % (n, n))
print(len(names), 'imports')
